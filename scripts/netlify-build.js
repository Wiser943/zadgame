// Runs on Netlify before publishing `public/`. Writes:
//   public/config.js  -> tells the browser where the backend lives
//   public/_redirects -> Netlify routing (+ API proxy in "proxy" mode)
//
// Netlify environment variables:
//   BACKEND_URL  (required) e.g. https://zadgame.onrender.com
//   API_MODE     "proxy" (default, recommended) or "direct"
const fs = require('fs'), path = require('path');
const backend = String(process.env.BACKEND_URL || '').trim().replace(/\/+$/, '');
const mode = (process.env.API_MODE || 'proxy').toLowerCase();
if (!/^https:\/\/[^/\s]+$/.test(backend)) { console.error('BACKEND_URL must be set to your Render URL, e.g. https://zadgame.onrender.com'); process.exit(1); }
if (!['proxy', 'direct'].includes(mode)) { console.error('API_MODE must be "proxy" or "direct"'); process.exit(1); }

const pub = path.join(__dirname, '..', 'public');
const cfg = mode === 'direct' ? { API_BASE: backend, SOCKET_URL: backend } : { API_BASE: '', SOCKET_URL: backend };
const f = path.join(pub, 'config.js');
const src = fs.readFileSync(f, 'utf8');
if (!/\/\*CFG\*\/[\s\S]*?\/\*END\*\//.test(src)) throw new Error('config.js markers missing');
fs.writeFileSync(f, src.replace(/\/\*CFG\*\/[\s\S]*?\/\*END\*\//, () => '/*CFG*/' + JSON.stringify(cfg) + '/*END*/'));

const proxy = mode === 'proxy' ? [
  `/api/*          ${backend}/api/:splat          200!`,
  `/auth/*         ${backend}/auth/:splat         200!`,
  `/admin-api/*    ${backend}/admin-api/:splat    200!`,
  `/lagosrun/api/* ${backend}/lagosrun/api/:splat 200!`,
  `/assets/*       ${backend}/assets/:splat       200!`,
  `/health         ${backend}/health              200!`,
  `/ready          ${backend}/ready               200!`,
  ''
] : [];
const rules = [
  '# generated by scripts/netlify-build.js',
  ...proxy,
  '# old GameHub invite/share links open GameHub; plain "/" is the AllConnect platform',
  '/   /index.html   200!   code=:code',
  '/   /index.html   200!   spectate=:s',
  '/   /index.html   200!   h=:h',
  '/   /index.html   200!   by=:by',
  '/   /allconnect/index.html   200!',
  '/gamehub    /index.html       200',
  '/advertise  /advertise.html   200',
  '/status     /status.html      200',
  '/stats      /stats.html       200',
  '/admin      /admin.html       200',
  '/lagosrun   /lagosrun/index.html 200',
  '# GameHub client-side routes (/lobby, /shop, ...)',
  '/*  /index.html  200'
];
fs.writeFileSync(path.join(pub, '_redirects'), rules.join('\n') + '\n');
console.log(`[netlify-build] mode=${mode} backend=${backend}`);
